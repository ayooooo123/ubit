struct SectionRange {
    double start = -1.0;
    double end = -1.0;
    bool active() const { return start >= 0.0 || end >= 0.0; }

    static double parse_ts(const std::string& raw) {
        std::string s = raw;
        while (!s.empty() && std::isspace((unsigned char)s.front())) s.erase(s.begin());
        while (!s.empty() && std::isspace((unsigned char)s.back())) s.pop_back();
        if (s.empty()) return -1.0;
        std::vector<double> parts;
        size_t pos = 0;
        while (true) {
            auto col = s.find(':', pos);
            std::string seg = (col == std::string::npos) ? s.substr(pos) : s.substr(pos, col - pos);
            char* ep = nullptr;
            double v = std::strtod(seg.c_str(), &ep);
            if (!ep || ep == seg.c_str()) return -1.0;
            parts.push_back(v);
            if (col == std::string::npos) break;
            pos = col + 1;
        }
        if (parts.size() == 1) return parts[0];
        if (parts.size() == 2) return parts[0] * 60.0 + parts[1];
        if (parts.size() == 3) return parts[0] * 3600.0 + parts[1] * 60.0 + parts[2];
        return -1.0;
    }

    static bool parse(const std::string& spec, SectionRange& out) {
        auto dash = spec.find('-');
        if (dash == std::string::npos) return false;
        std::string lhs = spec.substr(0, dash);
        std::string rhs = spec.substr(dash + 1);
        out.start = lhs.empty() ? -1.0 : parse_ts(lhs);
        out.end = rhs.empty() ? -1.0 : parse_ts(rhs);
        if (!lhs.empty() && out.start < 0) return false;
        if (!rhs.empty() && out.end < 0) return false;
        if (out.start >= 0 && out.end >= 0 && out.end <= out.start) return false;
        return out.active();
    }
};

