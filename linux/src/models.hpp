struct MediaFormat {
    std::string id;
    std::string url;
    std::string ext = "mp4";
    std::string proto = "http"; // "http", "hls", "dash"
    std::string vcodec;
    std::string acodec;
    int width = 0;
    int height = 0;
    double fps = 0.0;
    int64_t bitrate = 0;
    int64_t filesize = 0;
    std::string quality_label;
    std::map<std::string, std::string> headers;
    ByteRange init_range{0, -1};
    ByteRange index_range{0, -1};
    std::string audio_track_url;
    bool is_live = false;

    bool has_video() const {
        if (!vcodec.empty() && vcodec != "none") return true;
        return vcodec.empty() && height > 0;
    }
    bool has_audio() const {
        if (!audio_track_url.empty()) return true;
        if (!acodec.empty() && acodec != "none") return true;
        return acodec.empty() && !has_video();
    }
    bool is_h264() const {
        if (vcodec.empty()) return ext == "mp4" && has_video();
        std::string v = vcodec;
        for (char& c : v) c = (char)std::tolower((unsigned char)c);
        return v.find("avc") != std::string::npos || v.find("h264") != std::string::npos;
    }
    bool is_native_mp4() const { return ext == "mp4" || proto == "hls"; }
    bool is_aac() const {
        if (acodec.empty()) return (ext == "m4a" || ext == "mp4") && has_audio();
        std::string a = acodec;
        for (char& c : a) c = (char)std::tolower((unsigned char)c);
        return a.find("mp4a") != std::string::npos || a.find("aac") != std::string::npos;
    }
    std::string display_quality() const {
        if (!quality_label.empty()) return quality_label;
        if (height > 0) {
            if (fps > 31.0) return std::to_string(height) + "p" + std::to_string((int)std::round(fps));
            return std::to_string(height) + "p";
        }
        if (has_audio() && !has_video()) {
            if (bitrate > 0) return "Audio " + std::to_string(bitrate / 1000) + "k";
            return "Audio";
        }
        return id;
    }
    std::string short_codec() const {
        std::vector<std::string> parts;
        auto norm = [](std::string s) {
            for (char& c : s) c = (char)std::tolower((unsigned char)c);
            if (s.find("avc") != std::string::npos || s.find("h264") != std::string::npos) return std::string("h264");
            if (s.find("hev") != std::string::npos || s.find("hvc") != std::string::npos) return std::string("hevc");
            if (s.find("av01") != std::string::npos || s.find("av1") != std::string::npos) return std::string("av1");
            if (s.find("vp9") != std::string::npos || s.find("vp09") != std::string::npos) return std::string("vp9");
            if (s.find("mp4a") != std::string::npos || s.find("aac") != std::string::npos) return std::string("aac");
            if (s.find("opus") != std::string::npos) return std::string("opus");
            if (s.find("mp3") != std::string::npos) return std::string("mp3");
            auto dot = s.find('.');
            return dot == std::string::npos ? s : s.substr(0, dot);
        };
        if (!vcodec.empty() && vcodec != "none") parts.push_back(norm(vcodec));
        if (!acodec.empty() && acodec != "none") parts.push_back(norm(acodec));
        if (parts.empty()) return ext;
        return parts.size() == 2 ? (parts[0] + "+" + parts[1]) : parts[0];
    }

    Json to_json() const {
        Json j = Json::object();
        j["id"] = id;
        j["url"] = url;
        j["ext"] = ext;
        j["proto"] = proto;
        if (!vcodec.empty()) j["vcodec"] = vcodec;
        if (!acodec.empty()) j["acodec"] = acodec;
        if (width > 0) j["width"] = width;
        if (height > 0) j["height"] = height;
        if (fps > 0) j["fps"] = fps;
        if (bitrate > 0) j["bitrate"] = bitrate;
        if (filesize > 0) j["filesize"] = filesize;
        if (!quality_label.empty()) j["qualityLabel"] = quality_label;
        j["isLive"] = is_live;
        return j;
    }
};

