struct AppPaths {
    static fs::path temp_root() {
        if (const char* t = std::getenv("TMPDIR"); t && *t && ::access(t, W_OK) == 0) return fs::path(t);
        if (::access("/data/data/com.termux/files/usr/tmp", W_OK) == 0) return "/data/data/com.termux/files/usr/tmp";
        return "/tmp";
    }
    static fs::path home_dir() {
        if (const char* h = std::getenv("HOME"); h && *h) return fs::path(h);
        if (fs::exists("/data/data/com.termux/files/home")) return "/data/data/com.termux/files/home";
        return temp_root();
    }
    static fs::path config_dir() {
        if (const char* custom = std::getenv("UBIT_CONFIG_DIR"); custom && *custom) return fs::path(custom);
        if (const char* xdg = std::getenv("XDG_CONFIG_HOME"); xdg && *xdg) return fs::path(xdg) / "uBit";
        return home_dir() / ".config" / "uBit";
    }
    static fs::path downloads_dir() {
        fs::path termux_dl = home_dir() / "storage" / "downloads";
        if (fs::exists(termux_dl) && ::access(termux_dl.c_str(), W_OK) == 0) return termux_dl;
        if (::access("/sdcard/Download", W_OK) == 0) return "/sdcard/Download";
        fs::path d = home_dir() / "Downloads";
        std::error_code ec;
        fs::create_directories(d, ec);
        return fs::exists(d) ? d : home_dir();
    }
    static fs::path settings_file() { return config_dir() / "settings.json"; }
    static fs::path library_file()  { return config_dir() / "library.json"; }
    static fs::path subs_file()     { return config_dir() / "subscriptions.json"; }
    static fs::path cookies_file()  { return config_dir() / "cookies.txt"; }
    static fs::path work_dir()      { return config_dir() / "work"; }
    static fs::path ipc_socket()    { return config_dir() / "ubit.sock"; }

    static void ensure() {
        std::error_code ec;
        fs::create_directories(config_dir(), ec);
        fs::create_directories(work_dir(), ec);
        auto now = fs::file_time_type::clock::now();
        for (const auto& entry : fs::directory_iterator(work_dir(), ec)) {
            std::error_code ec2;
            auto mtime = fs::last_write_time(entry.path(), ec2);
            if (!ec2 && (now - mtime) > std::chrono::hours(24)) {
                fs::remove_all(entry.path(), ec2);
            } else if (entry.is_directory(ec2) && fs::is_empty(entry.path(), ec2)) {
                fs::remove_all(entry.path(), ec2);
            }
        }
    }
};

inline std::string expand_tilde(const std::string& p) {
    if (p == "~") return AppPaths::home_dir().string();
    if (p.rfind("~/", 0) == 0) return (AppPaths::home_dir() / p.substr(2)).string();
    if ((p == "/tmp" || p.rfind("/tmp/", 0) == 0) && ::access("/tmp", W_OK) != 0) {
        fs::path tr = AppPaths::temp_root();
        return p == "/tmp" ? tr.string() : (tr / p.substr(5)).string();
    }
    return p;
}

inline bool is_android_fuse_storage(const fs::path& p) {
    std::error_code ec;
    fs::path resolved = fs::weakly_canonical(p, ec);
    std::string s = ec ? p.string() : resolved.string();
    return s.rfind("/storage/", 0) == 0 || s.rfind("/sdcard/", 0) == 0 ||
           s.rfind("/mnt/", 0) == 0 || p.string().find("/storage/downloads") != std::string::npos;
}

/// Moves or streams `src` into `dst` safely across filesystems and Android Scoped Storage FUSE,
/// guaranteeing `fsync`, removing `src`, and verifying `dst` has exact non-zero byte length.
inline int64_t commit_file_verified(const fs::path& src, const fs::path& dst) {
    std::error_code ec;
    uintmax_t raw_sz = fs::file_size(src, ec);
    if (ec || raw_sz == 0 || raw_sz == (uintmax_t)-1) {
        throw std::runtime_error("Staged media file is empty (0 bytes): " + src.filename().string());
    }
    int64_t expected_sz = (int64_t)raw_sz;

    fs::create_directories(dst.parent_path(), ec);
    if (!fs::exists(dst.parent_path())) {
        throw std::runtime_error("Cannot create output directory: " + dst.parent_path().string());
    }

    if (!is_android_fuse_storage(dst) && ::rename(src.c_str(), dst.c_str()) == 0) {
        uintmax_t check_sz = fs::file_size(dst, ec);
        if (!ec && (int64_t)check_sz == expected_sz) return expected_sz;
    }

    int in_fd = ::open(src.c_str(), O_RDONLY);
    if (in_fd < 0) throw std::runtime_error("Cannot read staged file: " + src.string());

    int out_fd = ::open(dst.c_str(), O_CREAT | O_WRONLY | O_TRUNC, 0644);
    if (out_fd < 0) {
        ::close(in_fd);
        throw std::runtime_error("Cannot write to output path (check storage permissions / run termux-setup-storage): " + dst.string());
    }

    std::vector<uint8_t> buf(262144);
    int64_t total_written = 0;
    while (true) {
        ssize_t nr = ::read(in_fd, buf.data(), buf.size());
        if (nr < 0) {
            if (errno == EINTR) continue;
            ::close(in_fd); ::close(out_fd); ::unlink(dst.c_str());
            throw std::runtime_error("Read error while committing " + dst.filename().string());
        }
        if (nr == 0) break;
        size_t off = 0;
        while (off < (size_t)nr) {
            ssize_t nw = ::write(out_fd, buf.data() + off, (size_t)nr - off);
            if (nw < 0) {
                if (errno == EINTR) continue;
                ::close(in_fd); ::close(out_fd); ::unlink(dst.c_str());
                throw std::runtime_error("Write failed (disk full or permission denied): " + dst.string());
            }
            off += (size_t)nw;
        }
        total_written += nr;
    }
    ::fsync(out_fd);
    ::close(out_fd);
    ::close(in_fd);
    ::unlink(src.c_str());

    struct stat st{};
    if (::stat(dst.c_str(), &st) != 0 || st.st_size != expected_sz || total_written != expected_sz) {
        throw std::runtime_error("Output size verification failed for " + dst.string());
    }

    if (is_android_fuse_storage(dst)) {
        std::error_code ec_abs;
        std::string abs_dst = fs::weakly_canonical(dst, ec_abs).string();
        if (abs_dst.empty()) abs_dst = dst.string();
        if (std::system("command -v termux-media-scan >/dev/null 2>&1") == 0) {
            std::string scan_cmd = "termux-media-scan \"" + abs_dst + "\" >/dev/null 2>&1 &";
            (void)std::system(scan_cmd.c_str());
        } else if (::access("/system/bin/am", X_OK) == 0) {
            std::string am_cmd = "/system/bin/am broadcast -a android.intent.action.MEDIA_SCANNER_SCAN_FILE -d \"file://" + abs_dst + "\" >/dev/null 2>&1 &";
            (void)std::system(am_cmd.c_str());
        }
    }
    return expected_sz;
}

inline std::string format_bytes(int64_t b) {
    if (b < 1024) return std::to_string(b) + " B";
    const char* units[] = {"KB", "MB", "GB", "TB"};
    double v = (double)b;
    int idx = -1;
    while (v >= 1024.0 && idx < 3) { v /= 1024.0; ++idx; }
    char buf[64];
    std::snprintf(buf, sizeof(buf), v >= 100.0 ? "%.0f %s" : "%.1f %s", v, units[std::max(0, idx)]);
    return buf;
}

inline std::string format_duration(double sec) {
    if (!std::isfinite(sec) || sec < 0) return "0:00";
    int total = (int)std::round(sec);
    int h = total / 3600, m = (total % 3600) / 60, s = total % 60;
    char buf[64];
    if (h > 0) std::snprintf(buf, sizeof(buf), "%d:%02d:%02d", h, m, s);
    else std::snprintf(buf, sizeof(buf), "%d:%02d", m, s);
    return buf;
}

inline int64_t parse_rate_limit(std::string s) {
    while (!s.empty() && std::isspace((unsigned char)s.front())) s.erase(s.begin());
    while (!s.empty() && std::isspace((unsigned char)s.back())) s.pop_back();
    if (s.empty()) return 0;
    for (char& c : s) c = (char)std::toupper((unsigned char)c);
    double mult = 1.0;
    if (s.back() == 'B') s.pop_back();
    if (!s.empty() && s.back() == 'K') { mult = 1024.0; s.pop_back(); }
    else if (!s.empty() && s.back() == 'M') { mult = 1024.0 * 1024.0; s.pop_back(); }
    else if (!s.empty() && s.back() == 'G') { mult = 1024.0 * 1024.0 * 1024.0; s.pop_back(); }
    double v = std::atof(s.c_str());
    return v > 0 ? (int64_t)(v * mult) : 0;
}

inline std::string sanitize_filename(const std::string& raw) {
    std::string out;
    for (unsigned char c : raw) {
        if (c < 0x20 || c == '/' || c == '\\' || c == ':' || c == '*' || c == '?' || c == '"' || c == '<' || c == '>' || c == '|') {
            out.push_back('_');
        } else {
            out.push_back((char)c);
        }
    }
    while (!out.empty() && (out.front() == ' ' || out.front() == '.')) out.erase(out.begin());
    while (!out.empty() && out.back() == ' ') out.pop_back();
    if (out.empty()) out = "download";
    if (out.size() > 200) {
        size_t cut = 200;
        while (cut > 0 && ((unsigned char)out[cut] & 0xC0) == 0x80) --cut;
        out.resize(cut);
    }
    return out;
}

inline std::string render_template(const std::string& tpl, const MediaInfo& info, const std::string& qual, const std::string& ext) {
    std::string res = tpl.empty() ? "{title}" : tpl;
    auto repl = [&](const std::string& key, const std::string& val) {
        size_t p = 0;
        while ((p = res.find(key, p)) != std::string::npos) {
            res.replace(p, key.size(), val);
            p += val.size();
        }
    };
    repl("{title}", sanitize_filename(info.title));
    repl("{site}", sanitize_filename(info.site));
    repl("{author}", sanitize_filename(info.author.empty() ? "Unknown" : info.author));
    repl("{quality}", sanitize_filename(qual));
    repl("{date}", sanitize_filename(info.upload_date));
    repl("{id}", sanitize_filename(info.id));

    std::string cleaned;
    size_t start = 0;
    while (start <= res.size()) {
        auto sl = res.find('/', start);
        std::string seg = sanitize_filename(sl == std::string::npos ? res.substr(start) : res.substr(start, sl - start));
        if (!seg.empty()) {
            if (!cleaned.empty()) cleaned.push_back('/');
            cleaned += seg;
        }
        if (sl == std::string::npos) break;
        start = sl + 1;
    }
    if (cleaned.empty()) cleaned = sanitize_filename(info.title);
    return cleaned + "." + ext;
}

inline std::string read_file_text(const fs::path& p) {
    std::ifstream in(p, std::ios::binary);
    if (!in) return "";
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

inline void write_file_atomic(const fs::path& p, const void* data, size_t len) {
    std::error_code ec;
    fs::create_directories(p.parent_path(), ec);
    fs::path tmp = p;
    tmp += ".tmp";
    int fd = ::open(tmp.c_str(), O_CREAT | O_WRONLY | O_TRUNC, 0644);
    if (fd < 0) throw std::runtime_error("Cannot write " + p.string());
    size_t off = 0;
    while (off < len) {
        ssize_t nw = ::write(fd, (const uint8_t*)data + off, len - off);
        if (nw <= 0) { ::close(fd); ::unlink(tmp.c_str()); throw std::runtime_error("Disk write failed: " + p.string()); }
        off += (size_t)nw;
    }
    ::fsync(fd);
    ::close(fd);
    if (::rename(tmp.c_str(), p.c_str()) != 0) {
        if (len > 0) commit_file_verified(tmp, p);
        else ::unlink(tmp.c_str());
    }
}

